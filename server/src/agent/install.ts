import { createHash } from 'node:crypto';
import type { AgentBinary } from './binaries.ts';

/**
 * One-command agent installation.
 *
 * The copy-paste command downloads a generated install script and checks its SHA-256
 * (shown in the command) before running it. The script itself checks the agent binary
 * against embedded SHA-256 sums and enrols with --server-pin, so the HTTPS certificate of
 * the web front end does not have to be trusted by the client (local CA, IP address).
 * The enrollment token is passed as an argument and never part of the script or a URL.
 *
 * Scripts are deterministic (same inputs → same bytes), because the command pins their hash.
 * Keep them ASCII: Windows PowerShell 5.1 reads BOM-less .ps1 files in the ANSI code page.
 */

export const INSTALL_OS = ['linux', 'macos', 'windows'] as const;
export type InstallOs = (typeof INSTALL_OS)[number];

/** Must stay in sync with client.ServerPin in agent/internal/client/client.go. */
export function serverPin(caCertificate: string, signingPublicKey: string): string {
  return `sha256:${createHash('sha256').update(`${caCertificate}\n${signingPublicKey}`).digest('hex')}`;
}

export const sha256Hex = (s: string) => createHash('sha256').update(s, 'utf8').digest('hex');

const shq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
const psq = (s: string) => `'${s.replace(/'/g, "''")}'`;

function shaFor(binaries: AgentBinary[], os: InstallOs, arch: 'amd64' | 'arm64'): string {
  return binaries.find((b) => b.os === os && b.arch === arch)?.sha256 ?? '';
}

export function installScript(os: InstallOs, publicUrl: string, pin: string, binaries: AgentBinary[]): string {
  const base = publicUrl.replace(/\/$/, '');
  if (os === 'windows') return windowsScript(base, pin, binaries);
  const lines = [
    '#!/bin/sh',
    '# OpenCM agent installer - generated by the OpenCM server. Run as root.',
    '# Usage: sh opencm-install.sh <enrollment-token>',
    'set -eu',
    'TOKEN="${1:-}"',
    'fail() { echo "OpenCM: $*" >&2; exit 1; }',
    '[ -n "$TOKEN" ] || fail "usage: sh opencm-install.sh <enrollment-token>"',
    '[ "$(id -u)" = 0 ] || fail "please run as root (e.g. with sudo)"',
    'case "$(uname -m)" in',
    '  x86_64|amd64) ARCH=amd64 ;;',
    '  aarch64|arm64) ARCH=arm64 ;;',
    '  *) fail "unsupported architecture $(uname -m)" ;;',
    'esac',
    'case "$ARCH" in',
    `  amd64) SHA=${shq(shaFor(binaries, os, 'amd64'))} ;;`,
    `  arm64) SHA=${shq(shaFor(binaries, os, 'arm64'))} ;;`,
    'esac',
    `[ -n "$SHA" ] || fail "the server has no agent binary for ${os}/$ARCH"`,
    'if command -v sha256sum >/dev/null 2>&1; then sha() { sha256sum "$1" | cut -d" " -f1; }; else sha() { shasum -a 256 "$1" | cut -d" " -f1; }; fi',
    'TMP=$(mktemp)',
    "trap 'rm -f \"$TMP\"' EXIT",
    `echo "OpenCM: downloading agent (${os}/$ARCH) ..."`,
    '# -k: the binary is verified by its SHA-256 below instead of the HTTPS certificate',
    `curl -fsSLk ${shq(`${base}/api/v1/agent-downloads/${os}/`)}"$ARCH" -o "$TMP" || fail "download failed"`,
    '[ "$(sha "$TMP")" = "$SHA" ] || fail "checksum mismatch - aborting"',
    'mkdir -p /usr/local/bin',
    'cp "$TMP" /usr/local/bin/opencm-agent.new',
    'chmod 755 /usr/local/bin/opencm-agent.new',
    'mv -f /usr/local/bin/opencm-agent.new /usr/local/bin/opencm-agent',
    `/usr/local/bin/opencm-agent enroll --server ${shq(base)} --token "$TOKEN" --server-pin ${shq(pin)} || fail "enrollment failed"`,
    '/usr/local/bin/opencm-agent install || fail "service installation failed"',
    'echo "OpenCM: agent installed and running."',
  ];
  return `${lines.join('\n')}\n`;
}

function windowsScript(base: string, pin: string, binaries: AgentBinary[]): string {
  const lines = [
    '# OpenCM agent installer - generated by the OpenCM server. Run as Administrator.',
    'param([Parameter(Mandatory = $true)][string]$Token)',
    "$ErrorActionPreference = 'Stop'",
    '$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())',
    "if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'OpenCM: please run PowerShell as Administrator' }",
    "$arch = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'arm64' } else { 'amd64' }",
    `$sha = @{ amd64 = ${psq(shaFor(binaries, 'windows', 'amd64'))}; arm64 = ${psq(shaFor(binaries, 'windows', 'arm64'))} }[$arch]`,
    'if (-not $sha) { throw "OpenCM: the server has no agent binary for windows/$arch" }',
    '# the binary is verified by its SHA-256 below instead of the HTTPS certificate',
    '$web = @{ UseBasicParsing = $true }',
    'if ($PSVersionTable.PSVersion.Major -ge 6) { $web.SkipCertificateCheck = $true } else {',
    "  [Net.ServicePointManager]::SecurityProtocol = 'Tls12'",
    '  [Net.ServicePointManager]::ServerCertificateValidationCallback = { $true }',
    '}',
    "$dir = Join-Path $env:ProgramFiles 'OpenCM'",
    'New-Item -ItemType Directory -Force $dir | Out-Null',
    "$exe = Join-Path $dir 'opencm-agent.exe'",
    '$tmp = "$exe.download"',
    'Write-Host "OpenCM: downloading agent (windows/$arch) ..."',
    'try {',
    `  Invoke-WebRequest @web (${psq(`${base}/api/v1/agent-downloads/windows/`)} + $arch) -OutFile $tmp`,
    '} finally {',
    '  if ($PSVersionTable.PSVersion.Major -lt 6) { [Net.ServicePointManager]::ServerCertificateValidationCallback = $null }',
    '}',
    "if ((Get-FileHash $tmp -Algorithm SHA256).Hash -ne $sha) { Remove-Item $tmp; throw 'OpenCM: checksum mismatch - aborting' }",
    'Move-Item -Force $tmp $exe',
    `& $exe enroll --server ${psq(base)} --token $Token --server-pin ${psq(pin)}`,
    "if ($LASTEXITCODE -ne 0) { throw 'OpenCM: enrollment failed' }",
    '& $exe install',
    "if ($LASTEXITCODE -ne 0) { throw 'OpenCM: service installation failed' }",
    "Write-Host 'OpenCM: agent installed and running.'",
  ];
  return `${lines.join('\r\n')}\r\n`;
}

/**
 * Copy-paste one-liners. They run the script in its own shell/process, so an error never
 * closes the user's SSH session or PowerShell window.
 */
export function installCommands(publicUrl: string, token: string, scriptSha: Record<InstallOs, string>) {
  const base = publicUrl.replace(/\/$/, '');
  const unix = (os: 'linux' | 'macos') => {
    const check = os === 'linux' ? 'sha256sum -c -' : 'shasum -a 256 -c -';
    return (
      `f=$(mktemp) && curl -fsSLk ${shq(`${base}/api/v1/agent-install/${os}`)} -o "$f" && ` +
      `echo "${scriptSha[os]}  $f" | ${check} >/dev/null && sh "$f" ${shq(token)}; rm -f "$f"`
    );
  };
  const windows = [
    '$f = Join-Path $env:TEMP ("opencm-install-" + [guid]::NewGuid() + ".ps1"); $web = @{ UseBasicParsing = $true }',
    "if ($PSVersionTable.PSVersion.Major -ge 6) { $web.SkipCertificateCheck = $true } else { [Net.ServicePointManager]::SecurityProtocol = 'Tls12'; [Net.ServicePointManager]::ServerCertificateValidationCallback = { $true } }",
    `try { Invoke-WebRequest @web ${psq(`${base}/api/v1/agent-install/windows`)} -OutFile $f } finally { if ($PSVersionTable.PSVersion.Major -lt 6) { [Net.ServicePointManager]::ServerCertificateValidationCallback = $null } }`,
    `if ((Get-FileHash $f -Algorithm SHA256).Hash -ne ${psq(scriptSha.windows)}) { Remove-Item $f; throw 'OpenCM: install script checksum mismatch' }`,
    `powershell -NoProfile -ExecutionPolicy Bypass -File $f -Token ${psq(token)}; Remove-Item $f`,
  ].join('\n');
  return { windows, linux: unix('linux'), macos: unix('macos') };
}
